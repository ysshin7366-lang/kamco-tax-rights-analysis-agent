// 글 속에서 용어를 찾기 위한 표기 목록 (긴 표기를 먼저 찾아야 '가압류' 속 '압류'를 따로 세지 않는다)
const PATTERNS: { entry: GlossaryEntry; regex: RegExp }[] = GLOSSARY.map((entry) => {
  const alternatives = [...entry.match]
    .sort((a, b) => b.length - a.length)
    .map((text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    // '압류'는 '가압류'의 일부로 세지 않는다
    .map((text) => (text === "압류" ? "(?<!가)압류" : text));
  return { entry, regex: new RegExp(alternatives.join("|")) };
});

/** 글들에 나온 용어를 찾아, 처음 나온 순서대로 풀이 목록을 돌려준다. */
export function findTerms(texts: string[]): GlossaryEntry[] {
  const joined = texts.join("\n");
  return PATTERNS.map(({ entry, regex }) => ({ entry, index: joined.search(regex) }))
    .filter((hit) => hit.index >= 0)
    .sort((a, b) => a.index - b.index)
    .map((hit) => hit.entry);
}
