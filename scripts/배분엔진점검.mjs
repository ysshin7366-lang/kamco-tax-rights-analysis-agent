// 배분 계산 엔진 점검 (교육자료 배분사례 1~5 재현)
// 실행: node scripts/배분엔진점검.mjs   (모두 통과하면 종료 코드 0)
import { distribute, prorate } from "../src/lib/server/distribution.ts";
let fail = 0;
const M = 1_000_000;
const eq = (label, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "✓" : "✗", label, ok ? "" : `\n   결과 ${JSON.stringify(got)}\n   기대 ${JSON.stringify(want)}`); };
const C = (id, name, kind, amount, baseDate, lawDate = null) => ({ id, name, kind, label: kind, amount: amount * M, baseDate, lawDate });
const out = (r) => Object.fromEntries(r.allocations.map(a => [a.creditor.name, a.amount / M]));

// 교육자료 사례 1: 조세채권(압류·교부청구) 상호간 — 압류선착주의, 교부청구는 동순위 안분
let r = distribute({ fund: 51 * M, cost: 1 * M, creditors: [
  C("1", "A세무서", "조세", 10, "2020-06-01", "2020-01-25"), C("2", "B지자체", "조세", 20, "2021-01-01", "2019-12-25"),
  C("3", "C세무서", "조세", 50, null, "2018-10-25"), C("4", "D지자체", "조세", 50, null, "2018-06-10")] });
eq("사례1 압류선착주의 + 교부청구 동순위", [out(r), r.costPaid / M], [{ A세무서: 10, B지자체: 20, C세무서: 10, D지자체: 10 }, 1]);

// 사례 2: 납세담보는 압류선착주의에도 불구하고 우선
r = distribute({ fund: 51 * M, cost: 1 * M, creditors: [
  C("1", "A지자체", "조세", 10, "2019-12-01", "2019-06-30"), C("2", "B세무서", "조세", 20, "2020-03-01", "2018-12-31"),
  C("3", "C세무서", "조세", 10, null, "2019-01-31"), C("4", "D세무서", "납세담보", 30, "2020-12-10", "2020-12-01")] });
eq("사례2 납세담보 우선", out(r), { D세무서: 30, A지자체: 10, B세무서: 10, C세무서: 0 });

// 사례 3: 당해세는 압류선착주의 없이 우선(납세담보보다도)
r = distribute({ fund: 51 * M, cost: 1 * M, creditors: [
  C("1", "A지자체", "조세", 30, "2019-01-10", "2018-06-10"), C("2", "B지자체(당해세)", "당해세", 5, "2020-01-10", "2019-12-10"),
  C("3", "C세무서", "납세담보", 20, "2021-01-10", "2020-07-25"), C("4", "D세무서", "조세", 40, null, "2020-09-10"),
  C("5", "E지자체(당해세)", "당해세", 1, null, "2020-09-10")] });
eq("사례3 당해세 → 납세담보 → 압류선착", out(r), { "B지자체(당해세)": 5, "E지자체(당해세)": 1, C세무서: 20, A지자체: 24, D세무서: 0 });

// 사례 4: 담보채권·조세채권·공과금 — 법정기일·납부기한·설정일자 비교
r = distribute({ fund: 51 * M, cost: 1 * M, creditors: [
  C("1", "A세무서", "조세", 10, "2021-06-01", "2020-01-25"), C("2", "B지자체(당해세)", "당해세", 5, null, "2019-09-10"),
  C("3", "C공단", "공과금", 20, "2020-03-10", "2020-02-10"), C("4", "D은행", "담보", 35, "2020-06-01")] });
eq("사례4 당해세 → 조세 → 공과금 → 담보", out(r), { "B지자체(당해세)": 5, A세무서: 10, C공단: 20, D은행: 15 });

// 사례 5: 순환배분 (가압류 = 근저당, 조세 > 가압류, 근저당 > 조세)
r = distribute({ fund: 110 * M, cost: 10 * M, creditors: [
  C("1", "A채권(가압류)", "일반", 100, "2018-04-30"), C("2", "B세무서", "조세", 20, "2021-12-31", "2021-04-25"), C("3", "C은행", "담보", 80, "2020-02-01")] });
eq("사례5 순환배분(안분 후 흡수)", [out(r), r.circular.length], [{ "A채권(가압류)": 40, B세무서: 10, C은행: 50 }, 1]);
eq("사례5 1차 안분 50·10·40", r.circular[0].steps.map(s => s.firstShare / M), [50, 10, 40]);

// 안분 계산: 합계가 정확히 일치
eq("안분 합계 일치", prorate(100, [1, 1, 1]).reduce((a, b) => a + b, 0), 100);
// 자금이 충분하면 전액 배분 + 남은 돈
r = distribute({ fund: 100 * M, cost: 1 * M, creditors: [C("1", "은행", "담보", 30, "2020-01-01")] });
eq("채권보다 자금이 많으면 잔액 발생", [out(r), r.surplus / M], [{ 은행: 30 }, 69]);
// 자금이 강제징수비보다 적을 때
r = distribute({ fund: 500000, cost: 1 * M, creditors: [C("1", "은행", "담보", 30, "2020-01-01")] });
eq("강제징수비도 모자란 경우", [r.costPaid, out(r)], [500000, { 은행: 0 }]);
// 합계 보존
r = distribute({ fund: 80 * M, cost: 1 * M, creditors: [C("1", "A", "일반", 100, "2018-04-30"), C("2", "B", "조세", 20, "2021-12-31", "2021-04-25"), C("3", "C", "담보", 80, "2020-02-01")] });
eq("순환배분 합계 보존", r.costPaid + r.distributed + r.surplus, 80 * M);
// 항목 순서가 달라도 같은 결과
const cs = [C("1", "A", "일반", 100, "2018-04-30"), C("2", "B", "조세", 20, "2021-12-31", "2021-04-25"), C("3", "C", "담보", 80, "2020-02-01")];
eq("입력 순서가 달라도 같은 결과", JSON.stringify(out(distribute({ fund: 80 * M, cost: M, creditors: cs }))) === JSON.stringify(out(distribute({ fund: 80 * M, cost: M, creditors: [...cs].reverse() }))), true);
// '가압류는 항상 맨 뒤' 기준(generalLast): 사례 5와 같은 자료에서 순환배분 없이 조세·담보가 먼저, 가압류는 맨 뒤
r = distribute({ fund: 110 * M, cost: 10 * M, generalLast: true, creditors: [
  C("1", "A채권(가압류)", "일반", 100, "2018-04-30"), C("2", "B세무서", "조세", 20, "2021-12-31", "2021-04-25"), C("3", "C은행", "담보", 80, "2020-02-01")] });
const S = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1))); // 이름순으로 맞춰 비교
eq("가압류 맨 뒤 기준: 근저당(설정이 법정기일보다 빠름) → 조세 → 가압류", [S(out(r)), r.circular.length], [S({ "A채권(가압류)": 0, B세무서: 20, C은행: 80 }), 0]);
r = distribute({ fund: 60 * M, cost: 0, generalLast: true, creditors: [
  C("1", "A채권(가압류)", "일반", 100, "2018-04-30"), C("2", "B세무서", "조세", 20, "2019-12-31", "2019-04-25"), C("3", "C은행", "담보", 80, "2020-02-01")] });
eq("가압류 맨 뒤 기준: 법정기일이 설정일보다 빠르면 조세 먼저", S(out(r)), S({ "A채권(가압류)": 0, B세무서: 20, C은행: 40 }));
r = distribute({ fund: 25 * M, cost: 0, generalLast: true, creditors: [
  C("1", "A채권(가압류)", "일반", 100, "2018-04-30"), C("2", "B세무서", "조세", 20, "2021-12-31", "2021-04-25"), C("3", "C지자체", "조세", 30, "2022-03-01", "2021-11-01")] });
eq("가압류 맨 뒤 기준: 조세는 법정기일과 관계없이 압류선착주의 후 가압류", S(out(r)), S({ "A채권(가압류)": 0, B세무서: 20, C지자체: 5 }));

// 공과금은 가압류와 동순위(안분), 조세·담보보다 뒤 (generalLast)
r = distribute({ fund: 70 * M, cost: 0, generalLast: true, creditors: [
  C("1", "A채권(가압류)", "일반", 30, "2018-04-30"), C("2", "B공단", "공과금", 10, "2017-01-01"), C("3", "C은행", "담보", 20, "2020-02-01"), C("4", "D세무서", "조세", 10, "2021-12-31", "2021-04-25")] });
eq("공과금=가압류 동순위: 조세·담보 먼저, 남는 돈을 채권액 비율로 안분", S(out(r)), S({ "A채권(가압류)": 30, B공단: 10, C은행: 20, D세무서: 10 }));
r = distribute({ fund: 50 * M, cost: 0, generalLast: true, creditors: [
  C("1", "A채권(가압류)", "일반", 30, "2018-04-30"), C("2", "B공단", "공과금", 10, "2017-01-01"), C("3", "C은행", "담보", 20, "2020-02-01"), C("4", "D세무서", "조세", 10, "2021-12-31", "2021-04-25")] });
eq("공과금=가압류 동순위(부족): 20·10 먼저, 나머지 20을 30:10으로 안분", S(out(r)), S({ "A채권(가압류)": 15, B공단: 5, C은행: 20, D세무서: 10 }));
// 국세·지방세 압류끼리는 압류일자 순
r = distribute({ fund: 25 * M, cost: 0, generalLast: true, creditors: [
  C("1", "A세무서", "조세", 20, "2022-05-01", "2018-01-01"), C("2", "B시청", "조세", 20, "2021-05-01", "2020-01-01")] });
eq("조세 상호간: 법정기일과 관계없이 압류일자가 빠른 쪽 먼저", S(out(r)), S({ A세무서: 5, B시청: 20 }));

console.log(fail === 0 ? "\n전부 통과" : `\n실패 ${fail}건`);
process.exit(fail === 0 ? 0 : 1);


